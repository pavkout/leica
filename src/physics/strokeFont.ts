export const SUPPORTED_CHARS = Object.keys(GLYPHS).join("");

/** Characters the font can't draw (they're skipped), for a helpful message. */
export function unsupportedChars(text: string): string[] {
  return [...new Set([...text.toUpperCase()].filter((c) => !(c in GLYPHS)))];
}

/**
 * Lay out one line of text as strokes in the unit box [-1, 1]², centred and
 * scaled to fit (at most 1.8 wide, 1.1 tall). Unknown characters are skipped.
 */
export function textStrokes(text: string): { x: number; y: number }[][] {
  const chars = [...text.toUpperCase()].filter((c) => c in GLYPHS);
  if (chars.length === 0) return [];
  const width = chars.length * 5 - 1;
  const s = Math.min(1.8 / width, 1.1 / 6);
  const x0 = -(width * s) / 2;
  const y0 = -(6 * s) / 2;
  const out: { x: number; y: number }[][] = [];
  chars.forEach((c, i) => {
    for (const stroke of GLYPHS[c]) out.push(stroke.map(([gx, gy]) => ({ x: x0 + (i * 5 + gx) * s, y: y0 + gy * s })));
  });
  return out;
}
